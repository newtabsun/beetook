-- 2. Counting one reach -------------------------------------------------------------------------------------
-- Returns true when this viewer was newly counted. `delivered` is incremented under a row lock, so two
-- simultaneous viewers can never overshoot the goal, and only the transaction that flips the status may
-- write the completion alert (idempotent by construction).
CREATE OR REPLACE FUNCTION app_9e1318caf6_boost_reach_add(p_campaign bigint, p_viewer uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $f$
DECLARE c app_9e1318caf6_boost_campaigns; n integer; flipped boolean := false; unit text;
BEGIN
  IF p_campaign IS NULL OR p_viewer IS NULL THEN RETURN false; END IF;
  SELECT * INTO c FROM app_9e1318caf6_boost_campaigns WHERE id = p_campaign;
  IF c.id IS NULL OR c.status <> 'active' OR c.expires_at <= now() OR c.user_id = p_viewer THEN
    RETURN false;                                   -- finished, gone stale, or the owner themselves
  END IF;
  INSERT INTO app_9e1318caf6_boost_reach(campaign_id, user_id) VALUES (p_campaign, p_viewer)
    ON CONFLICT DO NOTHING;
  IF NOT FOUND THEN RETURN false; END IF;           -- this person was already reached by this boost
  UPDATE app_9e1318caf6_boost_campaigns
     SET delivered = LEAST(delivered + 1, goal), updated_at = now()
   WHERE id = p_campaign AND status = 'active'
   RETURNING delivered INTO n;
  IF n IS NULL THEN RETURN false; END IF;
  IF n < c.goal THEN RETURN true; END IF;

  UPDATE app_9e1318caf6_boost_campaigns
     SET status = 'completed', completed_at = now(), notified_at = now(), updated_at = now()
   WHERE id = p_campaign AND status = 'active'
   RETURNING true INTO flipped;
  IF NOT coalesce(flipped, false) THEN RETURN true; END IF;   -- another transaction already closed it

  unit := CASE c.kind WHEN 'views' THEN 'views' WHEN 'likes' THEN 'likes' WHEN 'comments' THEN 'comments'
                      WHEN 'profileViews' THEN 'profile views' ELSE 'live viewers' END;
  INSERT INTO app_9e1318caf6_notifications(user_id, actor_id, kind, text, ref_type, ref_id)
  VALUES (c.user_id, NULL, 'boost_done',
          'Your boost reached 100% — ' || to_char(c.goal, 'FM999G999G999') || ' ' || unit ||
          ' reached. Your video is now shown like any other post.',
          CASE WHEN c.post_id IS NULL THEN 'profile' ELSE 'post' END,
          coalesce(c.post_id::text, c.user_id::text));
  RETURN true;
END $f$;
REVOKE ALL ON FUNCTION app_9e1318caf6_boost_reach_add(bigint, uuid) FROM PUBLIC, anon, authenticated;

-- Maps a real audience action to the matching active campaign(s).
CREATE OR REPLACE FUNCTION app_9e1318caf6_boost_count_trg()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $f$
DECLARE r record; pid uuid; viewer uuid; k text;
BEGIN
  IF TG_TABLE_NAME = 'app_9e1318caf6_post_views' THEN pid := NEW.post_id; viewer := NEW.user_id; k := 'views';
  ELSIF TG_TABLE_NAME = 'app_9e1318caf6_likes' THEN pid := NEW.post_id; viewer := NEW.user_id; k := 'likes';
  ELSIF TG_TABLE_NAME = 'app_9e1318caf6_comments' THEN pid := NEW.post_id; viewer := NEW.user_id; k := 'comments';
  ELSIF TG_TABLE_NAME = 'app_9e1318caf6_live_viewers' THEN
    FOR r IN SELECT c.id FROM app_9e1318caf6_boost_campaigns c
               JOIN app_9e1318caf6_live_rooms lr ON lr.host_id = c.user_id
              WHERE lr.id = NEW.room_id AND c.kind = 'liveViewers'
                AND c.status = 'active' AND c.expires_at > now() LOOP
      PERFORM app_9e1318caf6_boost_reach_add(r.id, NEW.user_id);
    END LOOP;
    RETURN NULL;
  ELSIF TG_TABLE_NAME = 'app_9e1318caf6_profile_views' THEN
    FOR r IN SELECT c.id FROM app_9e1318caf6_boost_campaigns c
              WHERE c.kind = 'profileViews' AND c.status = 'active' AND c.expires_at > now()
                AND c.user_id = NEW.profile_id LOOP
      PERFORM app_9e1318caf6_boost_reach_add(r.id, NEW.viewer_id);
    END LOOP;
    RETURN NULL;
  ELSE
    RETURN NULL;
  END IF;
  IF pid IS NULL OR viewer IS NULL THEN RETURN NULL; END IF;
  FOR r IN SELECT c.id FROM app_9e1318caf6_boost_campaigns c
            WHERE c.post_id = pid AND c.kind = k AND c.status = 'active' AND c.expires_at > now() LOOP
    PERFORM app_9e1318caf6_boost_reach_add(r.id, viewer);
  END LOOP;
  RETURN NULL;
END $f$;
REVOKE ALL ON FUNCTION app_9e1318caf6_boost_count_trg() FROM PUBLIC, anon, authenticated;

