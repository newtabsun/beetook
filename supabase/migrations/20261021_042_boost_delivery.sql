-- 042 · Boost delivery: a boosted video is pinned for everybody until its goal is reached, the owner's
-- profile grid shows live progress, and 100 % is announced exactly once with no race.
-- Every decision lives here (campaigns + per-user reach + triggers + feed order); the app only displays.
-- Idempotent: safe to re-run.
BEGIN;

-- 1. Campaign state -----------------------------------------------------------------------------------------
-- One row per purchase. `goal` is what the buyer paid for, `delivered` counts *distinct* users reached.
CREATE TABLE IF NOT EXISTS app_9e1318caf6_boost_campaigns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  boost_id bigint REFERENCES app_9e1318caf6_video_boosts(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  post_id uuid REFERENCES app_9e1318caf6_posts(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('views', 'likes', 'comments', 'profileViews', 'liveViewers')),
  goal integer NOT NULL CHECK (goal > 0),
  delivered integer NOT NULL DEFAULT 0 CHECK (delivered >= 0),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'expired')),
  started_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '60 days',  -- safety net only: never sells forever
  completed_at timestamptz,
  notified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS app_9e1318caf6_boost_campaigns_boost ON app_9e1318caf6_boost_campaigns(boost_id);
CREATE INDEX IF NOT EXISTS app_9e1318caf6_boost_campaigns_post
  ON app_9e1318caf6_boost_campaigns(post_id, kind) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS app_9e1318caf6_boost_campaigns_owner ON app_9e1318caf6_boost_campaigns(user_id);

-- Who has already been reached by which boost: one row per (campaign, viewer), so repeats never count twice.
CREATE TABLE IF NOT EXISTS app_9e1318caf6_boost_reach (
  campaign_id bigint NOT NULL REFERENCES app_9e1318caf6_boost_campaigns(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (campaign_id, user_id)
);

-- Profile opens were never stored, so "profile views" boosts had nothing to count. Server-only table.
CREATE TABLE IF NOT EXISTS app_9e1318caf6_profile_views (
  profile_id uuid NOT NULL REFERENCES app_9e1318caf6_profiles(id) ON DELETE CASCADE,
  viewer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (profile_id, viewer_id)
);

ALTER TABLE app_9e1318caf6_boost_campaigns ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_9e1318caf6_boost_reach ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_9e1318caf6_profile_views ENABLE ROW LEVEL SECURITY;
