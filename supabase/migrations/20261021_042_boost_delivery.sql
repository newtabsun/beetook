       CASE WHEN b.quantity <= 0 THEN 'expired' ELSE 'active' END, NULL
  FROM app_9e1318caf6_video_boosts b
 WHERE NOT EXISTS (SELECT 1 FROM app_9e1318caf6_boost_campaigns c WHERE c.boost_id = b.id);

-- 4. Progress for the owner ("how far, how much is left") ---------------------------------------------------
CREATE OR REPLACE FUNCTION public.app_9e1318caf6_my_boosts()
RETURNS TABLE(campaign_id bigint, post_id uuid, kind text, goal integer, delivered integer,
              remaining integer, pct integer, status text, started_at timestamptz, completed_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $f$
  SELECT c.id, c.post_id, c.kind, c.goal, c.delivered, greatest(c.goal - c.delivered, 0),
         least(100, floor(c.delivered * 100.0 / greatest(c.goal, 1))::integer), c.status,
         c.started_at, c.completed_at
    FROM app_9e1318caf6_boost_campaigns c
   WHERE c.user_id = auth.uid() AND c.post_id IS NOT NULL
   ORDER BY (c.status = 'active') DESC, c.started_at DESC
$f$;
REVOKE ALL ON FUNCTION app_9e1318caf6_my_boosts() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION app_9e1318caf6_my_boosts() TO authenticated;

