REVOKE ALL ON FUNCTION app_9e1318caf6_normalize_username(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION app_9e1318caf6_username_error(text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION app_9e1318caf6_generate_username(bigint) FROM PUBLIC, anon, authenticated;

--------------------------------------------------------------------------------
-- 6. Guest lockdown: anonymous visitors read public content only
--------------------------------------------------------------------------------
-- Private tables: no anonymous SELECT at all (RLS already limits rows to their owner).
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'app_9e1318caf6_messages', 'app_9e1318caf6_message_hides', 'app_9e1318caf6_notifications',
    'app_9e1318caf6_wallets', 'app_9e1318caf6_wallet_txns', 'app_9e1318caf6_redeem_requests',
    'app_9e1318caf6_purchase_orders', 'app_9e1318caf6_market_orders', 'app_9e1318caf6_market_balances',
    'app_9e1318caf6_group_messages', 'app_9e1318caf6_group_earnings', 'app_9e1318caf6_support_messages',
    'app_9e1318caf6_user_settings', 'app_9e1318caf6_blocks', 'app_9e1318caf6_gifts',
    'app_9e1318caf6_live_joins', 'app_9e1318caf6_live_viewers', 'app_9e1318caf6_live_seats',
    'app_9e1318caf6_wagers'
  ] LOOP
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = t) THEN
      EXECUTE format('REVOKE SELECT ON public.%I FROM anon', t);
    END IF;
  END LOOP;
END $$;

