-- 035 · Readable Name vs. machine handle, generated `user<public_id>` handles, and guest lockdown.
--
-- Rules
--   * profiles.username is a handle: a-z 0-9 _ . only, 3–24 chars, no leading/trailing separator,
--     no `..`, lowercase, stored WITHOUT the leading `@` (the UI renders exactly one `@`).
--   * profiles.display_name is the human "Name": any script (incl. Amharic) and spaces.
--   * New accounts get `user<public_id>` (public_id starts at 10000001 → user10000001).
--   * Anonymous (guest) visitors never get a session or a row; they may only read public data.

--------------------------------------------------------------------------------
-- 1. Normalisation + validation
--------------------------------------------------------------------------------

-- Trims, drops every leading `@` and lowercases. `@@abebe`, `@abebe`, `  Abebe ` → `abebe`.
CREATE OR REPLACE FUNCTION app_9e1318caf6_normalize_username(p text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT lower(btrim(regexp_replace(btrim(coalesce(p, '')), '^@+', '')))
$$;

-- NULL when the handle is valid, otherwise a stable machine-readable reason.
CREATE OR REPLACE FUNCTION app_9e1318caf6_username_error(p text)
RETURNS text LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  u text := app_9e1318caf6_normalize_username(p);
BEGIN
  IF u = '' THEN RETURN 'empty'; END IF;
  IF u ~ '[^a-z0-9_.]' THEN
    IF EXISTS (SELECT 1 FROM regexp_split_to_table(u, '') ch WHERE ascii(ch) > 127) THEN
      RETURN 'non_ascii';
    END IF;
    RETURN 'invalid_chars';
  END IF;
  IF length(u) < 3 THEN RETURN 'too_short'; END IF;
  IF length(u) > 24 THEN RETURN 'too_long'; END IF;
  IF u ~ '^[._]' OR u ~ '[._]$' THEN RETURN 'bad_edges'; END IF;
  IF position('..' in u) > 0 THEN RETURN 'double_dot'; END IF;
  IF u = ANY (ARRAY['admin','administrator','support','beetook','api','www','live','market','inbox',
                    'profile','settings','help','about','login','signup','terms','privacy','wallet',
                    'official','root','moderator','staff','system','me','user','users']) THEN
    RETURN 'reserved';
  END IF;
  RETURN NULL;
END $$;

-- `user<public_id>`, falling back to `user<public_id>N` / a time suffix if that is already taken.
CREATE OR REPLACE FUNCTION app_9e1318caf6_generate_username(p_public_id bigint)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  base text := 'user' || COALESCE(p_public_id, 0)::text;
  cand text := base;
  n int := 0;
BEGIN
  WHILE EXISTS (SELECT 1 FROM app_9e1318caf6_profiles WHERE lower(username) = cand) LOOP
    n := n + 1;
    IF n > 50 THEN
      cand := 'user' || ((extract(epoch FROM clock_timestamp()) * 1000)::bigint % 1000000000)::text
              || (n % 97)::text;
    ELSE
      cand := base || n::text;
    END IF;
  END LOOP;
  RETURN cand;
END $$;

--------------------------------------------------------------------------------
-- 2. Sign-up trigger: Name from the form, handle generated by the server
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.app_9e1318caf6_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $function$
DECLARE
  v_name text;
BEGIN
  v_name := COALESCE(
    NULLIF(btrim(NEW.raw_user_meta_data->>'name'), ''),
    NULLIF(btrim(NEW.raw_user_meta_data->>'display_name'), ''),
    NULLIF(btrim(NEW.raw_user_meta_data->>'full_name'), ''),
    NULLIF(split_part(COALESCE(NEW.email, ''), '@', 1), '')
  );

  INSERT INTO app_9e1318caf6_profiles (id, username, display_name, phone)
  VALUES (
    NEW.id,
    NULL,
    v_name,
    NULLIF(btrim(COALESCE(NEW.raw_user_meta_data->>'phone', NEW.phone)), '')
  )
  ON CONFLICT (id) DO NOTHING;

  -- Handle needs the row's public_id, so it is assigned right after the insert.
  UPDATE app_9e1318caf6_profiles p
     SET username = app_9e1318caf6_generate_username(p.public_id)
   WHERE p.id = NEW.id
     AND (p.username IS NULL OR app_9e1318caf6_username_error(p.username) IS NOT NULL);

  INSERT INTO app_9e1318caf6_wallets(user_id) VALUES (NEW.id) ON CONFLICT DO NOTHING;
  RETURN NEW;
END $function$;

--------------------------------------------------------------------------------
-- 3. Backfill: normalise legacy handles, keep good ones, replace unusable ones
--------------------------------------------------------------------------------
DO $$
DECLARE
  r record;
  u text;
BEGIN
  FOR r IN SELECT id, username, public_id FROM app_9e1318caf6_profiles ORDER BY public_id LOOP
    u := app_9e1318caf6_normalize_username(r.username);
    IF u = ''
       OR app_9e1318caf6_username_error(u) IS NOT NULL
       OR EXISTS (SELECT 1 FROM app_9e1318caf6_profiles q WHERE q.id <> r.id AND lower(q.username) = u) THEN
      u := app_9e1318caf6_generate_username(r.public_id);
    END IF;
    IF u IS DISTINCT FROM r.username THEN
      UPDATE app_9e1318caf6_profiles SET username = u WHERE id = r.id;
    END IF;
  END LOOP;
END $$;

--------------------------------------------------------------------------------
-- 4. Constraints: one case-insensitive handle per person, format enforced by the DB
--------------------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS app_9e1318caf6_profiles_username_lower_key
  ON app_9e1318caf6_profiles (lower(username)) WHERE username IS NOT NULL;

ALTER TABLE app_9e1318caf6_profiles
  DROP CONSTRAINT IF EXISTS app_9e1318caf6_profiles_username_fmt;
ALTER TABLE app_9e1318caf6_profiles
  ADD CONSTRAINT app_9e1318caf6_profiles_username_fmt
  CHECK (username IS NULL OR (username = app_9e1318caf6_normalize_username(username)
                              AND app_9e1318caf6_username_error(username) IS NULL));

--------------------------------------------------------------------------------
-- 5. RPCs used by the client
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_9e1318caf6_username_available(p_username text)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  u text := app_9e1318caf6_normalize_username(p_username);
BEGIN
  IF app_9e1318caf6_username_error(u) IS NOT NULL THEN RETURN false; END IF;
  RETURN NOT EXISTS (
    SELECT 1 FROM app_9e1318caf6_profiles
     WHERE lower(username) = u AND (auth.uid() IS NULL OR id <> auth.uid())
  );
END $$;

CREATE OR REPLACE FUNCTION app_9e1318caf6_set_username(p_username text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  me uuid := auth.uid();
  u text;
  e text;
BEGIN
  IF me IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED' USING ERRCODE = '42501'; END IF;
  u := app_9e1318caf6_normalize_username(p_username);
  e := app_9e1318caf6_username_error(u);
  IF e IS NOT NULL THEN RAISE EXCEPTION 'USERNAME_%', upper(e) USING ERRCODE = '22023'; END IF;
  IF EXISTS (SELECT 1 FROM app_9e1318caf6_profiles WHERE lower(username) = u AND id <> me) THEN
    RAISE EXCEPTION 'USERNAME_TAKEN' USING ERRCODE = '23505';
  END IF;
  UPDATE app_9e1318caf6_profiles SET username = u WHERE id = me;
  RETURN u;
EXCEPTION
  WHEN unique_violation THEN RAISE EXCEPTION 'USERNAME_TAKEN' USING ERRCODE = '23505';
END $$;

REVOKE ALL ON FUNCTION app_9e1318caf6_set_username(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION app_9e1318caf6_set_username(text) TO authenticated;
REVOKE ALL ON FUNCTION app_9e1318caf6_username_available(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION app_9e1318caf6_username_available(text) TO authenticated;

